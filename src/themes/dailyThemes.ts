// Helper to create theme colors with sensible dark mode variants
function createColors(
  bgPrimary: string,
  bgSecondary: string,
  timerStart: string,
  timerMid: string,
  timerEnd: string,
  textPrimary: string,
  accent: string,
  gradientAngle: number = 135
): DailyThemeColors {
  return {
    backgroundPrimary: bgPrimary,
    backgroundSecondary: bgSecondary,
    backgroundGradient: `linear-gradient(${gradientAngle}deg, ${bgPrimary} 0%, ${bgSecondary} 100%)`,
    timerStart,
    timerMid,
    timerEnd,
    timerBackground: lighten(bgPrimary, 0.1),
    timerBackgroundDark: darken(bgPrimary, 0.7),
    timerInnerCircle: lighten(bgPrimary, 0.2),
    timerInnerCircleDark: darken(bgPrimary, 0.8),
    timerProgress: timerStart,
    timerProgressDark: timerMid,
    textPrimary,
    textPrimaryDark: lighten(textPrimary, 0.5),
    textSecondary: lighten(textPrimary, 0.2),
    textSecondaryDark: lighten(textPrimary, 0.3),
    accent,
    accentDark: lighten(accent, 0.2),
  };
}

// Simple color manipulation helpers
function lighten(hex: string, amount: number): string {
  const num = parseInt(hex.slice(1), 16);
  const r = Math.min(255, Math.round(((num >> 16) & 0xff) + (255 - ((num >> 16) & 0xff)) * amount));
  const g = Math.min(
    255,
    Math.round(((num >> 8) & 0xff) + (255 - ((num >> 8) & 0xff)) * amount)
  );
  const b = Math.min(255, Math.round((num & 0xff) + (255 - (num & 0xff)) * amount));
  return `#${((r << 16) | (g << 8) | b).toString(16).padStart(6, '0')}`;
}

function darken(hex: string, amount: number): string {
  const num = parseInt(hex.slice(1), 16);
  const r = Math.max(0, Math.round(((num >> 16) & 0xff) * (1 - amount)));
  const g = Math.max(0, Math.round(((num >> 8) & 0xff) * (1 - amount)));
  const b = Math.max(0, Math.round((num & 0xff) * (1 - amount)));
  return `#${((r << 16) | (g << 8) | b).toString(16).padStart(6, '0')}`;
}

