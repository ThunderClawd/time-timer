/**
 * Get all themes including special holiday themes
 */
export function getAllThemes(): DailyTheme[] {
  return [...DAILY_THEMES, ...SPECIAL_THEMES];
}

/**
 * Get a theme by its ID
 */
export function getThemeById(id: string): DailyTheme | undefined {
  return getAllThemes().find((theme) => theme.id === id);
}

/**
 * Get all themes for a specific season (excluding special themes)
 */
export function getThemesForSeason(season: Season): DailyTheme[] {
  return DAILY_THEMES.filter((theme) => theme.season === season);
}

/**
 * Get themes by category
 */
export function getThemesByCategory(category: ThemeCategory): DailyTheme[] {
  return getAllThemes().filter((theme) => theme.categories.includes(category));
}

/**
 * Check if a year is a leap year
 */
export function isLeapYear(year: number): boolean {
  return (year % 4 === 0 && year % 100 !== 0) || year % 400 === 0;
}

/**
 * Get day of year (1-366)
 */
export function getDayOfYear(date: Date): number {
  const start = new Date(date.getFullYear(), 0, 0);
  const diff = date.getTime() - start.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  return Math.floor(diff / oneDay);
}

/**
 * Get holiday theme for a specific date (if exists)
 */
export function getHolidayTheme(month: number, day: number): DailyTheme | null {
  const holiday = HOLIDAYS.find((h) => h.month === month && h.day === day);
  if (!holiday) return null;
  return SPECIAL_THEMES.find((t) => t.id === holiday.themeId) || null;
}

/**
 * Get the theme for a specific date
 */
export function getThemeForDate(date: Date): DailyTheme {
  const month = date.getMonth() + 1; // 1-indexed
  const day = date.getDate();

  // Check for holiday theme first
  const holidayTheme = getHolidayTheme(month, day);
  if (holidayTheme) {
    return holidayTheme;
  }

  // Get the current season
  const season = getCurrentSeason(date);

  // Get themes for this season
  const seasonThemes = getThemesForSeason(season);

  // Use day of year to pick a theme (modulo to cycle through themes)
  const dayOfYear = getDayOfYear(date);

  // Map day of year to theme index (ensuring variety across the season)
  const themeIndex = (dayOfYear - 1) % seasonThemes.length;

  const theme = seasonThemes[themeIndex];
  if (!theme) {
    // Fallback to first theme of season (should never happen)
    return seasonThemes[0]!;
  }
  return theme;
}
